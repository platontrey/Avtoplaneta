import 'package:freezed_annotation/freezed_annotation.dart';

part 'inventory_filter.freezed.dart';

@freezed
abstract class InventoryFilter with _$InventoryFilter {
  const InventoryFilter._();

  const factory InventoryFilter({
    @Default('') String search,
    @Default('') String category,
    @Default('') String brand,
    @Default('') String model,
    @Default('') String location,
    @Default('') String address,
    @Default('') String salesman,
    @Default('') String status,
    @Default('with') String hasPhoto,
    @Default('') String number,
    @Default('') String oemCode,
    @Default('') String vin,
    @Default('') String carReleasePeriod,
    @Default('') String bodyBrand,
    @Default('') String engineBrand,
    @Default('') String carReleaseDate,
    @Default('') String transmission,
    @Default('') String drive,
    @Default('') String condition,
    @Default('') String manufacturer,
    @Default('') String defect,
    @Default('') String color,
    @Default('') String minPrice,
    @Default('') String maxPrice,
    @Default('') String minQuantity,
    @Default('') String maxQuantity,
    @Default('') String frontRear,
    @Default('') String leftRight,
    @Default('') String topBottom,
    @Default('') String manufacturerCode,
    @Default('') String supplierCode,
    @Default('') String transmissionModel,
    @Default('') String wearPercentage,
    @Default('') String season,
    @Default('') String diameter,
    @Default('') String width,
    @Default('') String profile,
    @Default('') String tireQuantity,
    @Default('') String drilling,
    @Default('') String offset,
    @Default('') String centerHoleDiameter,
    @Default('') String tireModel,
    @Default('all') String pageSize,
    @Default(1) int page,
  }) = _InventoryFilter;

  int get activeFilterCount => [
    category,
    brand,
    model,
    location,
    address,
    salesman,
    status,
    hasPhoto == 'with' ? '' : hasPhoto,
    number,
    oemCode,
    vin,
    carReleasePeriod,
    bodyBrand,
    engineBrand,
    carReleaseDate,
    transmission,
    drive,
    condition,
    manufacturer,
    defect,
    color,
    minPrice,
    maxPrice,
    minQuantity,
    maxQuantity,
    frontRear,
    leftRight,
    topBottom,
    manufacturerCode,
    supplierCode,
    transmissionModel,
    wearPercentage,
    season,
    diameter,
    width,
    profile,
    tireQuantity,
    drilling,
    offset,
    centerHoleDiameter,
    tireModel,
    pageSize == 'all' ? '' : pageSize,
  ].where((value) => value.isNotEmpty).length;

  Map<String, dynamic> toQueryParameters({int? overrideLimit}) {
    final limitVal =
        overrideLimit ??
        (pageSize == 'all' ? 20 : (int.tryParse(pageSize) ?? 20));
    return {
      'page': page,
      'limit': limitVal,
      if (search.isNotEmpty) 'search': search,
      if (category.isNotEmpty) 'category': category,
      if (brand.isNotEmpty) 'brand': brand,
      if (model.isNotEmpty) 'model': model,
      if (location.isNotEmpty) 'location': location,
      if (address.isNotEmpty) 'address': address,
      if (salesman.isNotEmpty) 'salesman': salesman,
      if (status.isNotEmpty) 'status': status,
      if (hasPhoto != 'all') 'hasPhoto': hasPhoto,
      if (number.isNotEmpty) 'number': number,
      if (oemCode.isNotEmpty) 'oem_code': oemCode,
      if (vin.isNotEmpty) 'vin': vin,
      if (carReleasePeriod.isNotEmpty)
        'car_release_period': carReleasePeriod,
      if (bodyBrand.isNotEmpty) 'body_brand': bodyBrand,
      if (engineBrand.isNotEmpty) 'engine_brand': engineBrand,
      if (carReleaseDate.isNotEmpty) 'car_release_date': carReleaseDate,
      if (transmission.isNotEmpty) 'transmission': transmission,
      if (drive.isNotEmpty) 'drive': drive,
      if (condition.isNotEmpty) 'condition': condition,
      if (manufacturer.isNotEmpty) 'manufacturer': manufacturer,
      if (defect.isNotEmpty) 'defect': defect,
      if (color.isNotEmpty) 'color': color,
      if (minPrice.isNotEmpty) 'min_price': minPrice,
      if (maxPrice.isNotEmpty) 'max_price': maxPrice,
      if (minQuantity.isNotEmpty) 'min_quantity': minQuantity,
      if (maxQuantity.isNotEmpty) 'max_quantity': maxQuantity,
      if (frontRear.isNotEmpty) 'front_rear': frontRear,
      if (leftRight.isNotEmpty) 'left_right': leftRight,
      if (topBottom.isNotEmpty) 'top_bottom': topBottom,
      if (manufacturerCode.isNotEmpty)
        'manufacturer_code': manufacturerCode,
      if (supplierCode.isNotEmpty) 'supplier_code': supplierCode,
      if (transmissionModel.isNotEmpty)
        'transmission_model': transmissionModel,
      if (wearPercentage.isNotEmpty) 'wear_percentage': wearPercentage,
      if (season.isNotEmpty) 'season': season,
      if (diameter.isNotEmpty) 'diameter': diameter,
      if (width.isNotEmpty) 'width': width,
      if (profile.isNotEmpty) 'profile': profile,
      if (tireQuantity.isNotEmpty) 'tire_quantity': tireQuantity,
      if (drilling.isNotEmpty) 'drilling': drilling,
      if (offset.isNotEmpty) 'offset': offset,
      if (centerHoleDiameter.isNotEmpty)
        'center_hole_diameter': centerHoleDiameter,
      if (tireModel.isNotEmpty) 'tire_model': tireModel,
    };
  }
}
