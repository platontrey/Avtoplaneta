import type { Part } from '../types';

function formatPosition(frontRear?: string, leftRight?: string, topBottom?: string): string | null {
  const parts: string[] = [];
  if (frontRear) {
    if (frontRear.toUpperCase() === 'F' || frontRear.toLowerCase() === 'перед') parts.push('перед');
    else if (frontRear.toUpperCase() === 'R' || frontRear.toLowerCase() === 'зад') parts.push('зад');
    else parts.push(frontRear);
  }
  if (leftRight) {
    if (leftRight.toUpperCase() === 'L' || leftRight.toLowerCase() === 'лево') parts.push('лево');
    else if (leftRight.toUpperCase() === 'R' || leftRight.toLowerCase() === 'право') parts.push('право');
    else parts.push(leftRight);
  }
  if (topBottom) {
    if (topBottom.toUpperCase() === 'T' || topBottom.toUpperCase() === 'U' || topBottom.toLowerCase() === 'верх') parts.push('верх');
    else if (topBottom.toUpperCase() === 'B' || topBottom.toUpperCase() === 'D' || topBottom.toLowerCase() === 'низ') parts.push('низ');
    else parts.push(topBottom);
  }
  return parts.length > 0 ? parts.join(', ') : null;
}

/**
 * Генерирует читаемое описание запчасти на основе её технических характеристик,
 * если пользовательское описание не заполнено вручную.
 */
export function generatePartAutoDescription(part: Part): string {
  const segments: string[] = [];

  // Автомобиль и период выпуска
  const car = [part.brand?.trim(), part.model?.trim()].filter(Boolean).join(' ');
  const yearPeriod = part.car_release_period?.trim() || part.car_release_date?.trim();
  if (car) {
    segments.push(yearPeriod ? `Автомобиль: ${car} (${yearPeriod})` : `Автомобиль: ${car}`);
  } else if (yearPeriod) {
    segments.push(`Период выпуска: ${yearPeriod}`);
  }

  // Кузов и двигатель
  if (part.body_brand?.trim()) {
    segments.push(`Кузов: ${part.body_brand.trim()}`);
  }
  if (part.engine_brand?.trim()) {
    segments.push(`Двигатель: ${part.engine_brand.trim()}`);
  }

  // Сторона / расположение
  const pos = formatPosition(part.front_rear, part.left_right, part.top_bottom);
  if (pos) {
    segments.push(`Расположение: ${pos}`);
  }

  // OEM / Артикул / Номера
  if (part.oem_code?.trim()) {
    segments.push(`OEM: ${part.oem_code.trim()}`);
  }
  if (part.number?.trim() && part.number.trim() !== part.oem_code?.trim()) {
    segments.push(`Артикул: ${part.number.trim()}`);
  }
  if (part.manufacturer_code?.trim() && part.manufacturer_code.trim() !== part.number?.trim()) {
    segments.push(`Код произв.: ${part.manufacturer_code.trim()}`);
  }
  if (part.manufacturer?.trim()) {
    segments.push(`Производитель: ${part.manufacturer.trim()}`);
  }

  // Состояние и дефект
  if (part.condition?.trim()) {
    const cond = part.condition.trim();
    const wear = part.wear_percentage?.trim();
    segments.push(wear ? `Состояние: ${cond} (износ ${wear}%)` : `Состояние: ${cond}`);
  } else if (part.wear_percentage?.trim()) {
    segments.push(`Износ: ${part.wear_percentage.trim()}%`);
  }
  if (part.defect?.trim()) {
    segments.push(`Дефект: ${part.defect.trim()}`);
  }

  // Трансмиссия и привод
  if (part.transmission?.trim()) {
    const tModel = part.transmission_model?.trim();
    segments.push(tModel ? `КПП: ${part.transmission.trim()} (${tModel})` : `КПП: ${part.transmission.trim()}`);
  } else if (part.transmission_model?.trim()) {
    segments.push(`Модель КПП: ${part.transmission_model.trim()}`);
  }
  if (part.drive?.trim()) {
    segments.push(`Привод: ${part.drive.trim()}`);
  }

  // Цвет
  if (part.color?.trim()) {
    segments.push(`Цвет: ${part.color.trim()}`);
  }

  // Параметры шин и дисков
  const tireSpecs: string[] = [];
  if (part.tire_model?.trim()) tireSpecs.push(part.tire_model.trim());
  if (part.width?.trim() && part.profile?.trim() && part.diameter?.trim()) {
    tireSpecs.push(`${part.width.trim()}/${part.profile.trim()} R${part.diameter.trim()}`);
  } else if (part.diameter?.trim()) {
    tireSpecs.push(`R${part.diameter.trim()}`);
  }
  if (part.season?.trim()) tireSpecs.push(part.season.trim());
  if (tireSpecs.length > 0) {
    segments.push(`Параметры шин: ${tireSpecs.join(' ')}`);
  }

  // Склад и адрес
  if (part.location?.trim() || part.address?.trim()) {
    const loc = [part.location?.trim(), part.address?.trim()].filter(Boolean).join(', ');
    segments.push(`Склад: ${loc}`);
  }

  return segments.join('; ');
}

/**
 * Возвращает отображаемое описание детали и признак автогенерации.
 */
export function getPartDescriptionInfo(part?: Part | null): {
  description: string;
  isAutoGenerated: boolean;
} {
  if (!part) {
    return { description: '', isAutoGenerated: false };
  }

  const manual = part.description?.trim();
  if (manual) {
    return { description: manual, isAutoGenerated: false };
  }

  const auto = generatePartAutoDescription(part);
  return {
    description: auto,
    isAutoGenerated: auto.length > 0,
  };
}

/**
 * Возвращает текст описания детали (пользовательский или сформированный автоматически).
 */
export function getPartDescription(part?: Part | null): string {
  return getPartDescriptionInfo(part).description;
}
