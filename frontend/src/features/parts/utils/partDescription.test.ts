import { describe, it, expect } from 'vitest';
import { getPartDescriptionInfo, getPartDescription, generatePartAutoDescription } from './partDescription';
import type { Part } from '../types';

describe('partDescription utils', () => {
  it('returns manual description if present', () => {
    const part: Part = {
      id: 1,
      name: 'Бампер передний',
      quantity: 1,
      description: 'Оригинальный бампер в хорошем состоянии',
      brand: 'Toyota',
      model: 'Camry',
    };

    const info = getPartDescriptionInfo(part);
    expect(info.description).toBe('Оригинальный бампер в хорошем состоянии');
    expect(info.isAutoGenerated).toBe(false);
    expect(getPartDescription(part)).toBe('Оригинальный бампер в хорошем состоянии');
  });

  it('generates auto-description when manual description is empty or absent', () => {
    const part: Part = {
      id: 2,
      name: 'Дверь передняя левая',
      quantity: 2,
      description: '   ',
      brand: 'Honda',
      model: 'Civic',
      car_release_period: '2006-2011',
      body_brand: 'FD1',
      engine_brand: 'R18A',
      front_rear: 'F',
      left_right: 'L',
      oem_code: '67050-SNA-A00ZZ',
      condition: 'Контрактная',
      location: 'Стеллаж A-1',
    };

    const info = getPartDescriptionInfo(part);
    expect(info.isAutoGenerated).toBe(true);
    expect(info.description).toContain('Автомобиль: Honda Civic (2006-2011)');
    expect(info.description).toContain('Кузов: FD1');
    expect(info.description).toContain('Двигатель: R18A');
    expect(info.description).toContain('Расположение: перед, лево');
    expect(info.description).toContain('OEM: 67050-SNA-A00ZZ');
    expect(info.description).toContain('Состояние: Контрактная');
    expect(info.description).toContain('Склад: Стеллаж A-1');
  });

  it('handles empty part gracefully', () => {
    expect(getPartDescription(null)).toBe('');
    expect(getPartDescriptionInfo(undefined)).toEqual({ description: '', isAutoGenerated: false });

    const minimalPart: Part = {
      id: 3,
      name: 'Гайка',
      quantity: 10,
    };
    expect(generatePartAutoDescription(minimalPart)).toBe('');
    expect(getPartDescriptionInfo(minimalPart)).toEqual({ description: '', isAutoGenerated: false });
  });
});
